        if (prevMonthBtn) {
            prevMonthBtn.addEventListener('click', () => {
                currentDate.setMonth(currentDate.getMonth() - 1);
updateMonthDisplay();
                renderCalendar();
            });
        }

        if (nextMonthBtn) {
            nextMonthBtn.addEventListener('click', () => {
                currentDate.setMonth(currentDate.getMonth() + 1);
updateMonthDisplay();
                renderCalendar();
            });
        }

        if (todayBtn) {
            todayBtn.addEventListener('click', () => {
                const now = new Date();
                currentDate = new Date(now.getFullYear(), now.getMonth(), 1);
updateMonthDisplay();
                renderCalendar();
            });
        }

        if (jumpNextBatchBtn) {
            jumpNextBatchBtn.addEventListener('click', () => {
                const allBatches = batchData[currentCourseType] || [];
                const now = new Date();
                
                const upcoming = allBatches
                    .map(b => parseLocalDate(b.startDate))
                    .filter(d => d >= now)
                    .sort((a,b) => a-b);
                    
                if (upcoming.length > 0) {
                    currentDate = new Date(upcoming[0].getFullYear(), upcoming[0].getMonth(), 1);
                } else {
                    currentDate.setMonth(currentDate.getMonth() + 1);
                }
updateMonthDisplay();
                renderCalendar();
            });
        }

        if (partFilter) {
            partFilter.addEventListener('change', (e) => {
                selectedPartFilter = e.target.value;
                selectedBatchFilter = 'all';
                renderBatchList();
                renderCalendar();
            });
        }
        
        if (basicToggle) {
            basicToggle.addEventListener('click', () => switchCourseType('basic'));
        }

